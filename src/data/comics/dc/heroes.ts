import type { Character } from "../../types";
import { artFor } from "./art";

const E0 = "DC Universe — Earth-0";

/**
 * Folder convention (extensible, do not redo later):
 *   src/data/<category>/<universe>/<affiliation>.ts
 * Images: `image.url: null` = styled placeholder (uniform 3:4).
 * Licensed art later: 600x800 webp <200KB -> public/images/comics/dc/<id>.webp
 */
function hero(
  id: string,
  superName: string,
  name: string,
  universeLabel: string,
  teams: string[],
  gender: Character["gender"],
  species: Character["species"],
  powers: string[],
  comic: string,
  issue: string,
  year: number,
  bio: string
): Character {
  return {
    id,
    superName,
    name,
    category: "comics",
    universe: "dc",
    universeLabel,
    teams,
    affiliation: "hero",
    gender,
    species,
    powers,
    firstAppearance: { comic, issue, year },
    bio: `${name} is ${superName} of ${universeLabel}, affiliated with ${teams.join("; ")}. ${bio}`,
    image: artFor(id, superName),
  };
}

