const E0 = "DC Universe — Earth-0";

function antiHero(
  id: string,
  superName: string,
  name: string,
  universeLabel: string,
  teams: string[],
  gender: Character["gender"],
  species: Character["species"],
  powers: string[],
  comic: string,
  issue: string,
  year: number,
  bio: string
): Character {
  return {
    id,
    superName,
    name,
    category: "comics",
    universe: "dc",
    universeLabel,
    teams,
    affiliation: "anti-hero",
    gender,
    species,
    powers,
    firstAppearance: { comic, issue, year },
    bio: `${name} is ${superName} of ${universeLabel}, affiliated with ${teams.join("; ")}. ${bio}`,
    image: artFor(id, superName),
  };
}

